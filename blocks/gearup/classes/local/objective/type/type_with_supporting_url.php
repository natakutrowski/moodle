/**
 * Type.
 *
 * @package    block_gearup
 * @copyright  2024 Frédéric Massart
 * @author     Frédéric Massart <fred@branchup.tech>
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
interface type_with_supporting_url extends type {

    /**
     * Get the supporting URL.
     *
     * Returns the supporting URL from the objective type. The `$urlmode` is an integer
     * that is understood by the objective type to determine which URL to return.
     *
     * @param objective $objective The objective.
     * @param int $urlmode The URL mode.
     * @return moodle_url|null
     */
    public function get_supporting_url(objective $objective, $urlmode): ?moodle_url;

}
