 * @author     Frédéric Massart <fred@branchup.tech>
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
interface has_availability_info {

    /**
     * Get availability info.
     *
     * This should not perform any test on the current user. To determine whether
     * something is available for a particular user, refer to the other interface
     * {@link has_availiability_info_for_user}.
     *
     * @return info
     */
    public function get_availability_info(): info;

}
