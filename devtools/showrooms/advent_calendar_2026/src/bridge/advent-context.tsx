import React, {createContext, useCallback, useContext, useMemo, useRef, useState} from 'react';

export type Offer = {
  role: string; sku?: string; priceid?: number; currency?: string;
  available?: boolean; canbuy?: boolean; owned?: boolean; hasprice?: boolean;
  priceformatted?: string; cartaction?: string; sesskey?: string; returnurl?: string;
};
export type CurrencyOption = {value:string; label?:string; selected?:boolean; url?:string};
export type BridgePayload = {
  api:string; design:{id:string;version?:string};
  showroom:{key:string;language:string;currency:string;ispreview:boolean};
  content?:{page?:Record<string,string>};
  commerce?:{currency:string;offers:Offer[];currencies:CurrencyOption[]};
  links?:{support?:string;telegram?:string;whatsapp?:string;privacy?:string;terms?:string;offer?:string};
  legal?:Record<string,string>;
  media?:{previewAudioUrl?:string;storyCovers?:Record<number,string>};
};
export type AdventContextValue = {
  payload:BridgePayload; currency:string; offers:Offer[]; options:CurrencyOption[];
  busy:boolean;error:string;changeCurrency:(currency:string)=>Promise<void>;
  links:NonNullable<BridgePayload['links']>;media:NonNullable<BridgePayload['media']>;
};
const context=createContext<AdventContextValue|null>(null);
const langs=['ru','fr','en'];
const legalSelector='[data-showroom-final-legal]';

// Same bridge lifecycle as Articles: fetch the authorised next-currency showroom
// HTML, validate the embedded Commerce payload, and replace the native legal
// footer generated by Moodle. No page reload; never guess the legal seller.
export function AdventProvider({initial,children}:{initial:BridgePayload;children:React.ReactNode}) {
  const [payload,setPayload]=useState(initial);
  const [busy,setBusy]=useState(false);
  const [error,setError]=useState('');
  const nonce=useRef(0);
  const currency=payload.commerce?.currency||payload.showroom.currency||'EUR';
  const offers=payload.commerce?.offers||[];
  const options=payload.commerce?.currencies||[];
  const changeCurrency=useCallback(async (target:string)=>{
    if(target===currency || busy) return;
    // Build from the CURRENT, validated Commerce preview/public URL, exactly as
    // the working Articles showroom does. This keeps id, commerce_test and lang.
    const option=options.find(o=>o.value===target);
    if(!option || !/^[A-Z]{3}$/.test(target)){
      setError('change_error');return;
    }
    let url:URL;
    try{
      url=new URL(window.location.href);
      if(url.protocol!=='https:' || url.origin!==window.location.origin) throw new Error('invalid origin');
      url.searchParams.set('currency',target);
      url.hash='';
    }catch{
      setError('change_error');return;
    }
    const id=++nonce.current;
    let stage='network';
    let httpStatus=0;
    setBusy(true);setError('');
    try{
      const response=await fetch(url.href,{
        method:'GET',credentials:'same-origin',cache:'no-store',redirect:'error',
        headers:{Accept:'text/html'}
      });
      httpStatus=response.status;
      stage='http';
      if(!response.ok || response.redirected || new URL(response.url).origin!==window.location.origin ||
         new URL(response.url).pathname!==window.location.pathname) throw new Error('unexpected response');
      stage='payload';
      const doc=new DOMParser().parseFromString(await response.text(),'text/html');
      const script=doc.getElementById('campusfr-bridge-data');
      if(!script) throw new Error('missing data');
      const next=JSON.parse(script.textContent||'null') as BridgePayload;
      if(next?.api!==payload.api || next.design?.id!==payload.design.id ||
         next.showroom?.key!==payload.showroom.key ||
         next.showroom?.language!==payload.showroom.language ||
         next.showroom?.ispreview!==payload.showroom.ispreview ||
         next.showroom?.currency!==target || next.commerce?.currency!==target ||
         !Array.isArray(next.commerce?.offers) || next.commerce.offers.length>8 ||
         !Array.isArray(next.commerce?.currencies) ||
         !next.commerce.currencies.some(o=>o.value===target)) throw new Error('mismatched data');
      stage='offers';
      for(const offer of next.commerce.offers){
        if(!offer || typeof offer.role!=='string' || offer.currency!==target ||
           typeof offer.priceformatted!=='string' ||
           (offer.priceid!=null && (!Number.isSafeInteger(offer.priceid) || offer.priceid<0)) ||
           (offer.canbuy!==undefined && typeof offer.canbuy!=='boolean') ||
           (offer.available!==undefined && typeof offer.available!=='boolean')) {
          throw new Error('invalid offer');
        }
      }
      // Keep Commerce's SERVER-RENDERED legal footer. Never guess the seller.
      stage='footer';
      const nativeFooter=document.querySelector(legalSelector);
      const newFooter=doc.querySelector(legalSelector);
      if(!nativeFooter || !newFooter ||
         document.querySelectorAll(legalSelector).length!==1 ||
         doc.querySelectorAll(legalSelector).length!==1 ||
         newFooter.querySelector('script,style,form,iframe,object,embed,input,button')) {
        throw new Error('missing or unsafe legal footer');
      }
      if(id!==nonce.current)return;
      stage='history';
      window.history.replaceState(window.history.state,'',url.href);
      nativeFooter.replaceWith(document.importNode(newFooter,true));
      setPayload(next);
    }catch{
      if(id===nonce.current){
        // No URLs, HTML, personal data, payment IDs or tokens in the diagnostic.
        console.warn('[CampusFR Avent] currency refresh failed',{stage,httpStatus});
        setError('change_error');
      }
    }finally{
      if(id===nonce.current)setBusy(false);
    }
  },[currency,busy,options,payload]);
  const value=useMemo(()=>({payload,currency,offers,options,busy,error,changeCurrency,
    links:payload.links||{},media:payload.media||{}}),[payload,currency,offers,options,busy,error,changeCurrency]);
  return <context.Provider value={value}>{children}</context.Provider>;
}
export function useAdvent(){const value=useContext(context);if(!value)throw new Error('AdventProvider missing');return value;}
export function useT(){
  const {payload}=useAdvent();
  const lang=payload.showroom.language;
  if(!langs.includes(lang))throw new Error('Invalid language');
  return (key:string)=>payload.content?.page?.[key]||key;
}
